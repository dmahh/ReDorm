export const LANGS = ["kk", "ru", "en"] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = "kk";
export const LANG_COOKIE = "redorm.lang";

export const LANG_NAMES: Record<Lang, { short: string; full: string }> = {
  kk: { short: "ҚАЗ", full: "Қазақша" },
  ru: { short: "РУС", full: "Русский" },
  en: { short: "ENG", full: "English" },
};

export function isLang(v: unknown): v is Lang {
  return typeof v === "string" && (LANGS as readonly string[]).includes(v);
}

/** Picks the first supported language from an Accept-Language style list. */
export function pickLang(accept: string | null | undefined): Lang {
  if (!accept) return DEFAULT_LANG;
  for (const part of accept.split(",")) {
    const code = part.trim().split(";")[0]!.toLowerCase().split("-")[0];
    if (code === "kk" || code === "kz") return "kk";
    if (code === "ru") return "ru";
    if (code === "en") return "en";
  }
  return DEFAULT_LANG;
}

function ruPlural(n: number, one: string, few: string, many: string) {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}

