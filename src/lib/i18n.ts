export const DICTS: Record<Lang, Dict> = { kk, ru, en };

export function dict(lang: Lang): Dict {
  return DICTS[lang] ?? DICTS[DEFAULT_LANG];
}

/** Turns a server error / validation code into a message in the user's language. */
export function errorText(t: Dict, err: unknown, fallback: ErrorCode = "generic"): string {
  const code = err instanceof Error ? err.message : String(err);
  return (t.errors as Record<string, string>)[code] ?? t.errors[fallback];
}

export type PageKey = keyof Dict["meta"];

export function pageMeta(lang: Lang | undefined, page: PageKey) {
  const m = dict(lang ?? DEFAULT_LANG).meta[page];
  return [
    { title: m.title },
    { name: "description", content: m.description },
    { property: "og:title", content: m.title },
    { property: "og:description", content: m.description },
    { property: "og:type", content: "website" },
    { property: "og:locale", content: lang === "en" ? "en_US" : lang === "ru" ? "ru_RU" : "kk_KZ" },
    { name: "twitter:card", content: "summary_large_image" },
  ];
}
